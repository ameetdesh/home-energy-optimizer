def payload_block(indent: str, py_b64: str, var: str,
                  whl_b64: str | None, whl_name: str | None,
                  whl_note: str | None) -> str:
    L: list[str] = [BEGIN]
    if whl_b64:
        L += [
            f"// {whl_note}",
            f'const _whl = "{whl_b64}";',
        ]
    L += [
        "// Obfuscated Python UI/coordination code (zlib+base64)",
        f'const _pysrc = "{py_b64}";',
        "",
    ]
    if whl_b64:
        L += [
            "// Write the wheel into Pyodide's Emscripten FS and install from there.",
            "// emfs:// not file:// -- file:// is intercepted by the browser and",
            "// routed to the HTTP server, which 404s.",
            'await pyodide.loadPackage("micropip");',
            "await pyodide.runPythonAsync(`",
            "import base64, os",
            'os.makedirs("/tmp/wheels", exist_ok=True)',
            f'_whl_name = "{whl_name}"',
            'with open(f"/tmp/wheels/{_whl_name}", "wb") as f:',
            '    f.write(base64.b64decode("${_whl}"))',
            "import micropip",
            'await micropip.install(f"emfs:///tmp/wheels/{_whl_name}")',
            "`);",
            "",
        ]
    L += [
        f'const {var} = `import base64 as _b, zlib as _z; '
        f'exec(_z.decompress(_b.b64decode("${{_pysrc}}")))`;',
        END,
    ]
    # Only indent JS lines; the runPythonAsync template literal is Python
    # source where added leading whitespace would be a syntax error.
    inside_py = False
    out = []
    for line in L:
        if line.endswith("runPythonAsync(`"):
            out.append(indent + line)
            inside_py = True
            continue
        if inside_py:
            out.append(line)
            if line == "`);":
                inside_py = False
            continue
        out.append(indent + line if line else "")
    return "\n".join(out)


def splice(html: str, block: str) -> str:
    if BEGIN in html and END in html:
        return re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block,
                      html, flags=re.S)
    m = FETCH_RE.search(html)
    if not m:
        sys.exit("could not find an insertion point: no BEGIN/END markers and "
                 "no `const X = await (await fetch(...)).text();` loader line")
    return html[:m.start()] + block + html[m.end():]


def loader_var(html: str) -> str:
    if BEGIN in html:
        m = re.search(r"const (\w+) = `import base64 as _b", html)
        if m:
            return m.group(1)
    m = FETCH_RE.search(html)
    return m.group(1) if m else "code"


# ----------------------------------------------------------------------------

def main() -> None:
    ap = argparse.ArgumentParser(
        description="Build a self-contained Pyodide HTML page "
                    "(wasm wheel + obfuscated Python embedded).")
    ap.add_argument("--html", required=True, type=pathlib.Path,
                    help="source page (fetches the .py) or an existing standalone")
    ap.add_argument("--py", required=True, type=pathlib.Path,
                    help="Python module to obfuscate and embed")
    ap.add_argument("--out", required=True, type=pathlib.Path)

    g = ap.add_mutually_exclusive_group()
    g.add_argument("--wheel", type=str, help="prebuilt wasm32 wheel (glob ok)")
    g.add_argument("--build-wheel", action="store_true",
                   help="cross-compile build/*.pyx via Docker first")
    g.add_argument("--no-wheel", action="store_true",
                   help="pure-Python page, embed only the Python payload")

    ap.add_argument("--rebuild-image", action="store_true",
                    help="force a rebuild of the Docker builder image")
    ap.add_argument("--wasm-opt", action="store_true",
                    help="run binaryen wasm-opt -Oz over a freshly built wheel "
                         "(measured: ~1.1%%, 621B — rarely worth the extra pass)")
    ap.add_argument("--keep", action="append", default=[], metavar="NAME",
                    help="extra function name to leave unrenamed (repeatable)")
    ap.add_argument("--no-rename", action="store_true",
                    help="strip comments/docstrings but keep function names")
    ap.add_argument("--seed", type=int, default=0,
                    help="RNG seed for renaming; same seed = same output")
    args = ap.parse_args()

    html = args.html.read_text()
    py_src = args.py.read_text()

    # --- wheel ---------------------------------------------------------------
    whl_b64 = whl_name = whl_note = None
    if not args.no_wheel:
        if args.build_wheel:
            whl_path = build_wheel(args.rebuild_image)
            if args.wasm_opt:
                whl_path = wasm_opt(whl_path)
        elif args.wheel:
            hits = sorted(glob.glob(args.wheel))
            if not hits:
                sys.exit(f"no wheel matched {args.wheel!r}")
            whl_path = pathlib.Path(hits[0])
        else:
            hits = sorted(BUILD_DIR.glob("dist/*wasm32.whl"))
            if not hits:
                sys.exit("no wheel found in build/dist; pass --wheel, "
                         "--build-wheel, or --no-wheel")
            whl_path = hits[0]
        whl_note = describe_wheel(whl_path)
        whl_name = whl_path.name
        whl_b64 = base64.b64encode(whl_path.read_bytes()).decode()
        print(f"[wheel] {whl_name}  "
              f"{whl_path.stat().st_size:,}B -> {len(whl_b64):,} b64 chars")

    # --- python --------------------------------------------------------------
    spans = _template_spans(html)
    reserved = _reserved_from_html(html, spans) | set(args.keep)
    obf, mapping = obfuscate(py_src, reserved, args.seed,
                             rename=not args.no_rename)
    packed = zlib.compress(obf.encode(), 9)
    py_b64 = base64.b64encode(packed).decode()
    print(f"[py]    {len(py_src):,} chars -> {len(obf):,} obfuscated "
          f"-> {len(packed):,} zlib -> {len(py_b64):,} b64 chars "
          f"({len(mapping)} functions renamed)")

    # --- assemble ------------------------------------------------------------
    anchor = FETCH_RE.search(html)
    indent = (re.match(r"[ \t]*", anchor.group(0)).group(0)
              if anchor else "  ")
    # Mirror the renames into the page's embedded Python before splicing, so
    # runPythonAsync call sites still resolve.
    html, hits = rename_in_html(html, mapping, spans)
    print(f"[html]  {hits} call site(s) rewritten in "
          f"{len(spans)} template literal(s)")
    block = payload_block(indent, py_b64, loader_var(html),
                          whl_b64, whl_name, whl_note)
    args.out.write_text(splice(html, block))
    print(f"[out]   {args.out}  {args.out.stat().st_size:,} bytes")
    print("        serve over HTTP (file:// blocks the ES module import):")
    print(f"        python3 -m http.server 8765  ->  "
          f"http://localhost:8765/{args.out.name}")


if __name__ == "__main__":
    main()
