def _api(route, payload_json):
    """Single call the page makes. Mirrors battery/gui/server.py's /api/<route>.

    JSON strings in and out, so nothing crosses the JS/Python boundary as a
    proxy - the page parses the result exactly as it parses an HTTP response.
    """
    import json as _json
    try:
        return _json.dumps(call(route, _json.loads(payload_json or "{}")))
    except Exception as exc:  # surfaced in the page, as the server does
        return _json.dumps({"error": str(exc)})
