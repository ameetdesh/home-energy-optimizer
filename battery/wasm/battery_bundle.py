def _load_bus(z: Any) -> Bus | None:
    """A saved snapshot's bus chain (see PolicySnapshot.save), or None. A
    0.2.5/0.2.6 snapshot saved one level, flat."""
    if "bus_others" not in z:
        return None
    others, clip, sc = np.asarray(z["bus_others"]), np.asarray(z["bus_clip_cap"]), np.asarray(z["bus_scalars"])
    if others.ndim == 1:                                   # one level, the earlier layout
        return Bus((BusLevel(others, float(sc[0]), float(sc[1]), float(sc[2]), float(sc[3]), clip),),
                   float(sc[4]))
    levels = tuple(BusLevel(others[i], float(sc[i][0]), float(sc[i][1]), float(sc[i][2]), float(sc[i][3]), clip[i])
                   for i in range(len(others)))
    return Bus(levels, float(z["bus_breach_price"]))


@dataclass(frozen=True)
class PolicySnapshot:
    """Everything needed to evaluate the battery policy without re-solving.

    Deliberately self-contained and array-only so it can be persisted (.npz)
    and served by a process that never runs the solver.
    """

    horizon: Horizon
    battery: BatteryConfig
    value: np.ndarray  # V[t, s], shape (steps + 1, n_states)
    policy: np.ndarray  # POL[t, s], shape (steps, n_states)
    states: np.ndarray  # SoE grid, kWh
    actions: np.ndarray  # power action grid, kW
    buy: np.ndarray
    sell: np.ndarray
    dp_load: np.ndarray  # every other flow on the meter
    admm_target: np.ndarray | None = None
    admm_rho: float = 0.0
    generated_at: float = 0.0
    # The battery's chain of nodes, when it sits behind a sub-meter (a hybrid
    # inverter, a panel): actions are then bus-side, and reach the meter
    # through every level of it.
    bus: Bus | None = None

    @classmethod
    def from_result(
        cls, cfg: SiteConfig, fc: Forecasts, res: CoordinationResult
    ) -> PolicySnapshot:
        if "battery" not in res.devices:
            raise ValueError("result has no battery solution to snapshot")
        if cfg.battery is None:
            raise ValueError("site config has no battery")
        # Prefer the economics-only solve; fall back to the plan's own battery
        # solution only if pricing was not run.
        sol = res.battery_pricing or res.devices["battery"]
        if not isinstance(sol, DeviceSolution):
            raise ValueError("the battery was planned as an LP step and never priced: "
                             "it has no value function to snapshot")
        n = cfg.horizon.steps
        return cls(
            horizon=cfg.horizon,
            battery=cfg.battery,
            value=sol.value,
            policy=sol.policy,
            states=sol.states,
            actions=sol.actions,
            buy=(fc.buy if res.battery_tariff is None else res.battery_tariff[0]).copy(),
            sell=(fc.sell if res.battery_tariff is None else res.battery_tariff[1]).copy(),
            dp_load=(
                res.battery_dp_load.copy()
                if res.battery_dp_load is not None
                else np.zeros(n)
            ),
            generated_at=time.time(),
            bus=res.battery_bus,
        )

    # -- persistence --------------------------------------------------------

    def save(self, path: str) -> None:
        extra: dict[str, Any] = {} if self.bus is None else {
            "bus_others": np.array([lv.others for lv in self.bus.levels]),
            "bus_clip_cap": np.array([lv.clip_cap for lv in self.bus.levels]),
            "bus_scalars": np.array([[lv.eta_export, lv.eta_import, lv.export_cap, lv.import_cap]
                                     for lv in self.bus.levels]),
            "bus_breach_price": self.bus.breach_price}
        np.savez_compressed(
            path,
            **extra,
            value=self.value,
            policy=self.policy,
            states=self.states,
            actions=self.actions,
            buy=self.buy,
            sell=self.sell,
            dp_load=self.dp_load,
            admm_target=(
                self.admm_target if self.admm_target is not None else np.array([])
            ),
            admm_rho=self.admm_rho,
            generated_at=self.generated_at,
            dt=self.horizon.dt,
            hours=self.horizon.hours,
            capacity_kwh=self.battery.capacity_kwh,
            p_charge_max_kw=self.battery.p_charge_max_kw,
            p_discharge_max_kw=self.battery.p_discharge_max_kw,
            eta=self.battery.eta,
            eta_charge=self.battery.eta_c,
            eta_discharge=self.battery.eta_d,
            soc_initial_frac=self.battery.soc_initial_frac,
            soe_min_frac=self.battery.soe_min_frac,
        )

    @classmethod
    def load(cls, path: str) -> PolicySnapshot:
        z = np.load(path)
        target = z["admm_target"]
        return cls(
            horizon=Horizon(dt=float(z["dt"]), hours=float(z["hours"])),
            battery=BatteryConfig(
                capacity_kwh=float(z["capacity_kwh"]),
                p_charge_max_kw=float(z["p_charge_max_kw"]),
                p_discharge_max_kw=float(z["p_discharge_max_kw"]),
                eta=float(z["eta"]),
                eta_charge=float(z['eta_charge']),
                eta_discharge=float(z['eta_discharge']),
                # older snapshots predate the reserve
                soc_initial_frac=float(z["soc_initial_frac"]) if "soc_initial_frac" in z else 0.5,
                soe_min_frac=float(z["soe_min_frac"]) if "soe_min_frac" in z else 0.0,
                n_states=len(z["states"]),
                n_actions=len(z["actions"]),
            ),
            value=z["value"],
            policy=z["policy"],
            states=z["states"],
            actions=z["actions"],
            buy=z["buy"],
            sell=z["sell"],
            dp_load=z["dp_load"],
            admm_target=(target if target.size else None),
            admm_rho=float(z["admm_rho"]),
            generated_at=float(z["generated_at"]),
            bus=_load_bus(z),
        )

    # -- helpers ------------------------------------------------------------

    def step_for(self, hours_from_start: float) -> int:
        """Map wall-clock offset to a horizon step, clamped to the horizon."""
        return int(np.clip(round(hours_from_start / self.horizon.dt), 0, self.horizon.steps - 1))

    def _feasible_actions(self, soe: float) -> np.ndarray:
        feasible = _feasible_actions

        return feasible(
            self.actions,
            np.array(float(soe)),
            self.horizon.dt,
            self.battery.capacity_kwh,
            0.0,
            self.battery.charge_deadband_kw,
            self.battery.eta_c,
            self.battery.eta_d,
            self.battery.soe_floor_kwh,
        )


