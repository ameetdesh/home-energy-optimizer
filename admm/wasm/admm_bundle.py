def _api(route, payload_json):
    """Single call the page makes. Mirrors admm/gui/server.py's /api/<route>.

    Takes and returns JSON strings rather than objects, so nothing has to be
    converted across the JS/Python boundary by Pyodide's proxies - the page
    parses the result itself, exactly as it parses an HTTP response.
    """
    import json as _json
    try:
        return _json.dumps(call(route, _json.loads(payload_json or "{}")))
    except Exception as exc:  # surfaced in the UI, same as the server does
        return _json.dumps({"error": str(exc)})
