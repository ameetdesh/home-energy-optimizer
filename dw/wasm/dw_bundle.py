def _api(route, payload_json, progress=None):
    """Single call the page makes. Mirrors dw/gui/server.py's /api/<route>.

    JSON strings in and out, so nothing crosses the JS/Python boundary as a
    proxy - the page parses the result exactly as it parses an HTTP response.
    `progress(it, max_iter)`, if given, is the worker's callback: it posts
    each iteration to the page while the solve is still running.
    """
    import json as _json
    try:
        return _json.dumps(call(route, _json.loads(payload_json or "{}"), progress))
    except Exception as exc:  # surfaced in the UI, as the server does
        return _json.dumps({"error": str(exc)})
